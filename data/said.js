/**
 * ผู้เรียนเคยพิมพ์คำสั่งที่ตรงกับ `re` ไปแล้วไหม
 *
 * เทียบสองรูป: รูปที่พิมพ์จริง และรูปที่ขยาย path สัมพัทธ์เป็น path เต็มแล้ว
 * (`history.abs` ที่ js/terminal.js เก็บคู่กันมา)
 *
 * เหตุผล: ตัวตรวจ task เกือบทั้งหมดเขียน regex ด้วย path เต็ม เช่น
 * `/cat\s+\/tmp\/README/` แต่ผู้เรียนที่ `cd /tmp` ก่อนแล้วพิมพ์ `cat README_RESTORE.txt`
 * ทำถูกทุกอย่างกลับไม่ผ่าน — เทียบรูปที่ขยายแล้วด้วยจึงยืดหยุ่นพอโดยไม่ต้องแก้ทีละ Lab
 *
 * เทียบรูปดิบ "ก่อน" เสมอ เพื่อให้ตัวตรวจที่จงใจมองหาคำสั่งแบบสัมพัทธ์ยังทำงานเหมือนเดิม
 *
 * @param {string[]} h  ประวัติคำสั่งที่ทำงานสำเร็จ (อาจมี .abs ติดมาด้วย)
 * @param {RegExp} re
 */
export const said = (h, re) => {
  if (!h || !h.length) return false;
  if (h.some(c => re.test(String(c).trim()))) return true;
  const abs = h.abs;
  return Array.isArray(abs) && abs.some(c => re.test(String(c).trim()));
};

/**
 * ผู้เรียนพิมพ์คำสั่งที่ตรงกับ `re` ไปกี่ครั้ง — ใช้กับ task ที่ต้องทำซ้ำ
 * เช่น "ทดสอบก่อนแก้ แล้วทดสอบอีกครั้งหลังแก้"
 *
 * นับรายคำสั่ง ไม่ใช่รายรูป — คำสั่งเดียวที่ตรงทั้งรูปดิบและรูป path เต็ม นับเป็นหนึ่ง
 */
export const times = (h, re) => {
  if (!h || !h.length) return 0;
  const abs = Array.isArray(h.abs) ? h.abs : [];
  return h.reduce((n, c, i) =>
    n + (re.test(String(c).trim()) || re.test(String(abs[i] ?? '').trim()) ? 1 : 0), 0);
};

/** บรรทัดที่มีเนื้อหาจริงในไฟล์ — ตัดช่องว่างหัวท้ายและบรรทัดว่างทิ้ง */
export const linesOf = (content) =>
  String(content ?? '').split('\n').map((x) => x.trim()).filter(Boolean);

/**
 * ไฟล์นี้มีครบทุกบรรทัดที่ขอไหม — ใช้กับ task ที่สั่งให้ "ต่อท้าย"
 *
 * เดิมตรวจแค่ว่าข้อความใหม่โผล่ในไฟล์ ผู้เรียนที่ใช้ `>` เขียนทับจึงผ่านไปได้
 * ทั้งที่บรรทัดเดิมหายไปหมดแล้ว ซึ่งตรงข้ามกับสิ่งที่บทเรียนสอน
 * (`>` เขียนทับ · `>>` ต่อท้าย) — มีผู้เรียนรายงานเข้ามาจริง
 *
 * เทียบทีละบรรทัดด้วย ไม่ใช่ค้นทั้งก้อน เพราะ `echo "a b" > f` ก็ทำให้
 * การค้นหาคำว่า a และ b เจอทั้งคู่ได้ ทั้งที่มีอยู่บรรทัดเดียว
 */
export const hasLines = (content, ...patterns) => {
  const lines = linesOf(content);
  return patterns.every((re) => lines.some((l) => re.test(l)));
};
