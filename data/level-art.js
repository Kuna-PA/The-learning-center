/** คำบรรยายภาพ — ใช้เป็น alt ให้โปรแกรมอ่านหน้าจอและตอนภาพโหลดไม่ขึ้น */
const ALT = {
  1: 'ผู้เรียนมือใหม่นั่งอ่านเอกสารหน้าคอมพิวเตอร์',
  2: 'ผู้ดูแลระบบมือใหม่กำลังพิมพ์คำสั่งพื้นฐานบนเทอร์มินัล',
  3: 'วิศวกรดูแลตู้แร็คและเฝ้าแผนที่เครือข่ายด้วยตัวเอง',
  4: 'วิศวกรไล่ปัญหาจากหลายหน้าจอพร้อมผังและกราฟ',
  5: 'ผู้เชี่ยวชาญด้านความปลอดภัยเฝ้าระวังภัยคุกคาม',
  6: 'ผู้ดูแลระบบมองภาพรวมทั้งองค์กรจากศูนย์ควบคุม',
};

const LEVELS_WITH_ART = [1, 2, 3, 4, 5, 6];

/**
 * ภาพของระดับที่ขอ — ระดับที่ยังไม่มีภาพจะใช้ของระดับ 1 แทนเพื่อไม่ให้การ์ดว่าง
 * คืนเป็น <img> ไม่ใช่ <svg> จึงต้องกำหนดขนาดจาก CSS ของที่ที่เอาไปวาง (.lv-art)
 */
export function levelArt(n) {
  const lv = LEVELS_WITH_ART.includes(+n) ? +n : 1;
  return `<img class="lv-art" src="assets/levels/lv${lv}.png" alt="${ALT[lv]}" loading="lazy" decoding="async">`;
}
